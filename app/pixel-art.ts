export function paintAvatar(ctx: CanvasRenderingContext2D, look: AvatarLook) {
  const skin = skinTones[look.skin];
  const color = hairColors[look.color];
  const hair = hairShapes[look.hair];
  const headwear = headwearArt[look.headwear];
  const accessory = accessoryArt[look.accessory];
  const woman = look.body === "woman";
  const sweater = woman
    ? { base: "#378b77", light: "#69c2a1", shade: "#245f60" }
    : { base: "#a94856", light: "#e27a73", shade: "#72384c" };

  function block(fill: string, x: number, y: number, width: number, height = 1) {
    ctx.fillStyle = fill;
    ctx.fillRect(x, y, width, height);
  }

  function layer(fill: string, blocks: readonly Block[]) {
    for (const [x, y, width, height] of blocks) block(fill, x, y, width, height);
  }

  function outline(fill: string, blocks: readonly Block[]) {
    for (const [x, y, width, height = 1] of blocks) {
      block(edge, x - 1, y, width + 2, height);
      block(edge, x, y - 1, width, height + 2);
    }
    layer(fill, blocks);
  }

  function paintCosmetic({ base, details }: Cosmetic) {
    outline(base[0], base[1]);
    for (const [fill, blocks] of details) layer(fill, blocks);
  }

  function paintHair(paint: () => void) {
    const hairline = headwear?.hairline;
    if (hairline === undefined) {
      paint();
      return;
    }

    ctx.save();
    ctx.beginPath();
    ctx.rect(7, hairline, 18, 2);
    ctx.rect(6, hairline + 2, 20, 1);
    ctx.rect(0, hairline + 3, 32, 32 - hairline - 3);
    ctx.clip();
    paint();
    ctx.restore();
  }

  ctx.clearRect(0, 0, 32, 32);

  const backHair = hair.back;
  if (backHair) paintHair(() => outline(color.shade, backHair));

  outline(sweater.base, woman
    ? [[11, 25, 10, 1], [8, 26, 16, 2], [6, 28, 20, 4]]
    : [[10, 25, 12, 1], [7, 26, 18, 1], [5, 27, 22, 2], [4, 29, 24, 3]]);
  layer(sweater.light, [[8, 27, 5], [19, 27, 5], [7, 30, 18]]);
  layer(sweater.shade, [[8, 31, 16], [9, 29, 1, 3], [22, 29, 1, 3]]);
  layer(sweater.shade, woman
    ? [[12, 25, 8], [13, 26, 6], [14, 27, 4]]
    : [[11, 25, 10], [12, 26, 8], [13, 27, 6]]);

  outline(skin.shade, [[7, 15, 2, 4], [23, 15, 2, 4]]);
  outline(skin.base, [[11, 6, 10], [9, 7, 14, 2], [8, 9, 16, 12], [9, 21, 14, 2], [11, 23, 10], [13, 24, 6]]);
  layer(skin.light, [[11, 7, 10], [10, 9, 11, 3], [9, 12, 2, 6], [10, 19, 2, 2], [12, 22, 5]]);
  layer(skin.shade, [[22, 12, 1, 9], [20, 21, 2], [18, 23, 2], [16, 17, 2, 2]]);
  block(skin.shade, 14, 25, 4, 2);
  block(skin.base, 14, 25, 2, 2);

  layer(color.shade, [[11, 13, 3], [19, 13, 3]]);
  layer("#fff0db", [[11, 15, 3, 2], [19, 15, 3, 2]]);
  layer(edge, [[12, 15, 2, 2], [19, 15, 2, 2]]);
  block(edge, 14, look.detail === "mustache" ? 22 : 21, 4);

  switch (look.detail) {
    case "freckles":
      layer(skin.shade, [[10, 18, 1], [12, 19, 1], [13, 18, 1], [19, 18, 1], [20, 19, 1], [22, 18, 1]]);
      break;
    case "blush":
      layer("#d47276", [[10, 18, 3], [20, 18, 3]]);
      break;
    case "mustache":
      layer(color.base, [[11, 19, 1], [13, 19, 6], [20, 19, 1], [11, 20, 10]]);
      layer(color.light, [[13, 19, 2], [17, 19, 2]]);
      block(color.shade, 12, 20, 8);
      break;
    case "beard":
      layer(color.base, [[9, 17, 2, 3], [21, 17, 2, 3], [9, 20, 3, 2], [20, 20, 3, 2], [10, 22, 12], [11, 23, 10], [13, 24, 6]]);
      layer(color.light, [[10, 19, 1], [21, 19, 1], [11, 22, 2], [19, 22, 2], [14, 23, 4]]);
      layer(color.shade, [[9, 20, 1, 2], [22, 20, 1, 2], [13, 24, 6]]);
      break;
    case "bandage":
      layer("#f3c990", [[14, 17, 5, 2]]);
      layer("#cc9567", [[16, 17, 1], [17, 18, 1]]);
      break;
    case "mole":
      block("#4f2d2b", 20, 20, 1);
      break;
    case "stud":
      block("#b98148", 17, 18, 2);
      block("#ffe497", 18, 17, 1);
      break;
    case "goatee":
      layer(color.shade, [[15, 22, 3], [14, 23, 5], [15, 24, 3]]);
      block(color.light, 16, 23, 2);
      break;
  }

  if (accessory?.underHair) paintCosmetic(accessory);

  paintHair(() => {
    outline(color.base, hair.front);
    if (hair.fade && hair.fadeEdge) {
      const previousAlpha = ctx.globalAlpha;
      ctx.globalAlpha = previousAlpha * 0.62;
      layer(color.base, hair.fade);
      ctx.globalAlpha = previousAlpha * 0.28;
      layer(color.base, hair.fadeEdge);
      ctx.globalAlpha = previousAlpha;
    }
    if (hair.shade) layer(color.shade, hair.shade);
    if (hair.light) layer(color.light, hair.light);
    if (hair.ties) layer("#f3c280", hair.ties);
  });

  if (accessory && !accessory.underHair) paintCosmetic(accessory);

  switch (look.eyewear) {
    case "round":
      layer("#f5ce77", [[11, 13, 3], [19, 13, 3], [10, 14, 1, 4], [14, 14, 1, 4], [18, 14, 1, 4], [22, 14, 1, 4], [11, 18, 3], [19, 18, 3], [15, 15, 3]]);
      break;
    case "square":
      layer("#463c5a", [[9, 13, 7], [17, 13, 7], [9, 14, 1, 5], [15, 14, 1, 5], [17, 14, 1, 5], [23, 14, 1, 5], [10, 18, 5], [18, 18, 5], [16, 15, 1]]);
      layer("#c1b3cc", [[10, 13, 4], [18, 13, 4]]);
      break;
    case "shades":
      layer(edge, [[9, 14, 15], [10, 15, 5, 4], [17, 15, 6, 4]]);
      layer("#746481", [[11, 15, 3], [18, 15, 4], [11, 16, 1], [18, 16, 1]]);
      break;
    case "stars":
      layer("#d19b4e", [[11, 13, 2, 2], [8, 15, 8], [9, 16, 6], [10, 17, 4], [9, 18, 2], [13, 18, 2], [19, 13, 2, 2], [16, 15, 8], [17, 16, 6], [18, 17, 4], [17, 18, 2], [21, 18, 2]]);
      layer("#ffe28b", [[11, 14, 2], [9, 15, 2], [13, 15, 2], [19, 14, 2], [17, 15, 2], [21, 15, 2]]);
      layer(edge, [[11, 15, 2, 2], [19, 15, 2, 2]]);
      break;
  }

  if (headwear) paintCosmetic(headwear);
}
